def _cnt_bgr(img, bgr):
    """画面里**正好**是这个颜色的像素数（BGR ✓）。⚠ `cv2` 画线/画框都是**整元组纯色** ⇒ 逐像素
    相等就数得准 ✓（⚠ 但**1px ＋ `LINE_AA`** 的细线**没有纯色像素** ✗ 见 `_cnt_aa` ✓）。"""
    return int(np.all(np.asarray(img) == np.array(bgr, np.uint8), axis=2).sum())


def _aa_mask(img, bgr, tol=40):
    """**颜色家族掩膜**（BGR ✓）：每个分量都差 ≤ `tol` 的像素 ⇒ `True`。**一处口径** ✓。

    ⚠⚠⚠ **为什么"逐像素精确相等"不够** ✗✗（**实测** ✓：本文件 `test_box_label_two_lines` 的
      那个标签夹具，同一段代码在两种 opencv 上跑）：
        · **opencv 5.0** ⇒ `(0,255,255)` 纯色像素 **209 个** ✓（它把最饱和的那些落回纯色 ✓）；
        · **opencv 4.14** ⇒ 纯色像素 **0 个** ✗（每个笔画像素都被灰底混过 ✓）；
      而**两版都真把字画出来了**（这一带非零像素 1694 / 2144 ✓）。
      ⇒ 凡是量"**AA 画出来的字 / 细线**"，一律按**颜色家族**数 ✓（本掩膜 ✓）；
        量"**粗线 / 填充**"（无 AA ⇒ 本来就有纯色像素 ✓）才用精确口径（`_cnt_bgr` ✓）。
    ⚠ 容差取 **40**（**实测夹出来的** ✓）：同一夹具按"黄像素按行分组"看 ——
        · `tol=20` ⇒ opencv 5 是 **2** 组、**opencv 4 碎成 5 组** ✗（只捞到最饱和的几粒 ✓）；
        · `tol=40` ⇒ **两版都恰好 2 组** ✓（opencv 5 = 418px ／ opencv 4 = 242px ✓）；
        · `tol=60` ⇒ 也是 2 组 ✓（余量更大，但更容易与别的黄色件串 ✓ ⇒ 停在 40 ✓）。
    """
    _a = np.asarray(img).astype(np.int16)
    _t = np.array(bgr, np.int16)
    return np.all(np.abs(_a - _t) <= int(tol), axis=2)


def _cnt_aa(img, bgr, tol=40):
    """**颜色家族**的像素数（分量各自差 ≤ `tol` ✓）—— 专门给 **1px ＋ `LINE_AA`** 那种细线/字用。

    ⚠⚠ **为什么非有它不可** ✗✗（**实测** ✓）：`cv2.line(..., (0,170,170), 1, cv2.LINE_AA)` 画一条
      60px 横线 ⇒ 纯色像素 **0 个** ✗（AA 把颜色摊到相邻两行 ⇒ 每行只有一半亮度 ✓）；而
      "**有没有画**"这件事必须量得出来 ✓ ⇒ 退一步按"**颜色家族**"数 ✓（暗黄那条线 60px ⇒ 上百
      像素 ✓ 远超 `LINE_AA` 边缘蹭出来的那几个 ✓）。
    ⚠⚠ 口径**就在 `_aa_mask` 一处** ✗（本条只是它的计数视图 ✓ 容差 40 的来路见那里 ✓）。
    """
    return int(np.count_nonzero(_aa_mask(img, bgr, tol)))


#: ⚠ 这些项**必须按颜色家族量**（1px ＋ `LINE_AA` ⇒ 没纯色像素 ✓ 见 `_cnt_aa` ✓）。
_AA_KEYS = ("暗黄线（鼠标相对群体）",)


def _cnt_item(img, key, bgr):
    """按这一项的**画法**选量法（细线 ⇒ 颜色家族 ✓ 其余 ⇒ 纯色 ✓）。"""
    return (_cnt_aa(img, bgr) if key in _AA_KEYS else _cnt_bgr(img, bgr))


