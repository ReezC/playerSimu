        self.on_board = False
        #: ⭐ **最后一次被配到的时刻**（判"还钉得住吗" ✓ 见 `_BOARD_HOLD_S` ✓）。
        self.hit_ts = ts
        #: ⭐⭐ **它是不是"真目标那一格"**（用户 2026-09-30 ✓）：判据 = **中心落在红框内 且
        #:   离追踪器 `pos` 最近** ✓（融合期红框里通常正好是"真目标 + 被融合的那块假砖"两条 ✓，
