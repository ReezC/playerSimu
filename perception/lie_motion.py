    def _pair(self, dets):
        """本拍框 ↔ 已有轨迹 **一对一**配对（贪心 ✓）。

        ⚠ 用轨迹的**观测位置**（不是预测位置 ✗）当基准 —— 相机一帧走几十 px、目标非匀速 ✓
          ⇒ 预测反而可能更远 ✗；**门限 70px** 已经足够宽 ✓（实测配对门限 70 时中位偏离只 4px ✓）。

        ⚠⚠⚠ **贪心顺序 = 先看「轨迹可信度」、再看距离** ✗✗（**这一行是实测逼出来的** ✓）：
          原来是**纯距离优先** ✗ ⇒ 一个框同时落在两条轨迹门口时，**离得近的那条**赢 ✓
          —— 哪怕它只是个分数很低的壳 ✗ ⇒ **真目标反而配不上** ✓✗。
          实测（用户 2026-10-03 ✓ **帧 13** ✓，逐框量过 ✓）：
            · 真目标 `#13`（score **175.6** ✓ 上一拍在 (355,269)）⇒ 预期 (377,278)；
            · 本拍**离它最近的框是 (354,311)，距 41px** ✓ **在门限 70 以内** ✓ ⇒ **本该配上** ✗；
            · 但 `#11`（score 只有 **32.2** ✗，上一拍在 (345,303)）离那个框**只有 12px** ✗✗
            ⇒ **纯距离贪心让 `#11` 抢走** ⇒ `#13` 出局 ⇒ 位置只能"按相机中位推" ✗
            ⇒ 帧 13、14 **连着两拍目标都是 `DEAD`**（用户看到的就是这个 ✓✗）。
          ⇒ 改成 **`(-score, 距离)` 排序** ✓ ⇒ **分高的先挑** ✓ ⇒ `#13` 抢回自己的框 ✓✓。
          ⚠ 为什么现在才敢用 `score` 排序 ✗：因为它的**虚高已经被修掉了** ✓（`mv` 归一化成
            "每拍" + `prev` 顺序对调 ✓ 见 `_Track.mv_span` ✓）—— 修之前那条"跨拍位移"的幽灵
            分数**虚高** ✗ ⇒ 拿它排序只会**更糟** ✓（先修量纲、再改排序 ✓ 顺序不能反 ✗）。
        """
        _cand = []
        for _j, _b in enumerate(dets):
            _cx, _cy = float(_b[1]), float(_b[2])
            # ⚠⚠⚠ **第一轮只让「活跃的」轨迹参与** ✗✗（`miss == 0` ✓）—— ⚠ 这是**实测逼出来的**
            #   （用户 2026-10-03 那条诉求 ✓ 见 `_REVIVE_GATE` ✓）：原来**所有**轨迹一起进第一轮 ✓
            #   而排序是 `-score` ⇒ **高分（活跃）的优先** ✗ ⇒ **睡着的**（`miss > 0` ✓ 分数一直在
            #   衰减 ✓）**永远抢不到自己的框** ✗ ⇒ 它的框被"路过的活跃轨迹"拿走 ✗ ⇒ 框不够分 ⇒
            #   **它再现时只能新建** ✗✗（实测：全片建过 35 条而假目标只 ~15 个 ✓ 加复活轮也只从
            #   36 降到 35 ✗ 就是这个原因 ✓）。
            #   ⇒ 现在分工清楚：**活跃的**用严门限（`pair_gate` 70 ✓）、**睡着的**一律留到第二轮
            #     用宽门限（`revive_gate` 110 ✓）接 ✓ ⇒ **各回各家，不互相抢** ✓✓。
            for _t in self.tracks:
                if _t.miss > 0:
                    continue
                # ⭐⭐⭐ **基准 = 「预测位置」`_t.pred`** ✓（上一拍用 KF 算出来的"本拍它应该在哪儿" ✓）
                #   —— 原来是"**上一拍观测**"✗：目标**自己每拍还要动 20 多 px** ✓ ⇒ 预测能把这部分
                #   **先补上** ✓ ⇒ 离真位置更近 ⇒ **不容易被旁边的框抢走** ✓✓
                #   （实测帧 13 就是被"离得更近的邻居"抢走的 ✓ 见下面 `(-score, 距离)` 那段 ✓）。
                _d = math.hypot(_cx - _t.pred[0], _cy - _t.pred[1])
                if _d <= self.pair_gate:
                    _cand.append((-_t.score, _d, _t.id, _j))
        _cand.sort()
        _pairs, _used_t, _used_d = [], set(), set()
        for _s, _d, _tid, _j in _cand:
            if _tid in _used_t or _j in _used_d:
                continue
            _used_t.add(_tid)
            _used_d.add(_j)
            _pairs.append((_tid, _j))
        # ⭐⭐⭐ **第二轮：把"没配上的框"接回"睡着的旧轨迹"**（**保住原 id** ✓ 见 `_REVIVE_GATE` ✓）
        #   用户 2026-10-03 原话："假目标……**是不会凭空消失**的，它的**检出框消失后很短时间内
        #   再被检出**" ✓ ⇒ 那就该**接着用原来的 id** ✓ 而不是当新目标 ✗（实测：全片建过 **36** 条
        #   而假目标只有 ~15 个 ✗ 多出来那一倍就是在这里漏的 ✓）。
        #   ⚠ 两个限定（**保守** ✓ 别把两个不同目标接错 ✗）：
        #     ① 只在"**睡着的**"轨迹里找（`miss > 0` ✓ —— 本轮**已经配上框**的那些不许抢 ✗）；
        #     ② 门限放宽到 `revive_gate`（它消失那几拍只能靠"群体中位"外推 ⇒ 有累积误差 ✓）。
        #   ⚠ 排序用**纯距离** ✗（不是 `-score` ✓）：复活要的是"**位置最像**"✓ 不是"谁分高"✓。
        _sleep = [t for t in self.tracks if t.id not in _used_t and t.miss > 0]
        if _sleep and len(_used_d) < len(dets):
            _c2 = []
            for _j, _b in enumerate(dets):
                if _j in _used_d:
                    continue
                _cx, _cy = float(_b[1]), float(_b[2])
                for _t in _sleep:
                    _d = math.hypot(_cx - _t.pred[0], _cy - _t.pred[1])
                    if _d <= self.revive_gate:
                        _c2.append((_d, _t.id, _j))
            _c2.sort()
            for _d, _tid, _j in _c2:
                if _tid in _used_t or _j in _used_d:
                    continue
                _used_t.add(_tid)
                _used_d.add(_j)
                _pairs.append((_tid, _j))
        return _pairs, _used_d

    def _dir_votes(self, dets):
        """**本拍「几何运动」给各方向投的票** ✓（用户 2026-10-04 ✓ 见 `_DIR_N` 那段 ✓）。

        ⚠⚠ **算法就三步**（就是用户那句话的落地 ✓："**所有在群体坐标系中的几何运动**都会影响
        **这些方向的置信度**" ✓）：
          ① **追同一个框**：本拍每个框，去上一拍的框里找**中心最近**的那个 ✓
             （⚠⚠ **别用"框中心取整当键"** ✗ —— 中心每拍都在动 ⇒ 键每拍都变 ⇒ **永远对不上** ✗
              我第一版就是这么错的，量出来的是**跨不同框**的差值 ✓ 用户当场指出 ✓）；
          ② **算四条边的「相对群体位移」** ✓：`Δ边 = (本拍边 − 上拍边) − 相机位移` ✓
             —— 「边的位置」= 中心 ± 半宽 / 半高 ✓；减掉相机 ⇒ 得到**相对群体**的运动 ✓；
          ③ **每条边投一票** ✓：把它的位移向量 `(Δx, Δy)` 按**角度**插值进 N 格 ✓
             权重 = `|Δ| ÷ 噪声底` ✓（⚠ 与 `q` **同一套口径** ✓ 无量纲 ⇒ **换素材不用改** ✓）；
             太小的（`< _DIR_VOTE_K × 噪声底`）**不投** ✓（防抖 ✓）。

        ⚠ **为什么"边"能指出真目标在哪** ✓：单个目标尺寸不变 ✓ ⇒
          · **整框一起平移** ⇒ 四条边**同向** ✓（= "它整体在往那走" ✓）；
          · **只有一条边在动** ⇒ **说明有个目标在那条边上进出** ✓✓
            （= 融合框里"真目标往哪走"的**直接证据** ✓ 实测帧 20~24 上边持续向上 ✓）。
        ⚠ **框还没配对时也能算** ✓（只依赖"框"本身 ✓）⇒ 正好补上"轨迹还没归属"那段空档 ✓。
        """
        _conf = [0.0] * self.dir_n
        _noise = max(1.0, float(self._dev_med))
        _med = tuple(self._median_mv) if hasattr(self, "_median_mv") else (0.0, 0.0)
        # ---- ① 收齐："每个框的四条边"在群体坐标系里各挪了多少 ----
        _items = []                                            # `[(边号 0上1下2左3右, dx, dy)]`
        for _b in dets:
            _cx, _cy = float(_b[1]), float(_b[2])
            _w0, _h0 = float(_b[3]), float(_b[4])
            _pb, _bd = None, 1e9
            for _p in self._prev_boxes:
                _d = math.hypot(_p[0] - _cx, _p[1] - _cy)
                if _d < _bd:
                    _bd, _pb = _d, _p
            if _pb is None or _bd > self.pair_gate * 2.0:      # 追不到 ⇒ 没有"前后"可比 ✓
                continue
            _items.append((0, (_cy - _h0 / 2.0) - (_pb[1] - _pb[3] / 2.0) - _med[1]))
            _items.append((1, (_cy + _h0 / 2.0) - (_pb[1] + _pb[3] / 2.0) - _med[1]))
            _items.append((2, (_cx - _w0 / 2.0) - (_pb[0] - _pb[2] / 2.0) - _med[0]))
            _items.append((3, (_cx + _w0 / 2.0) - (_pb[0] + _pb[2] / 2.0) - _med[0]))
        # ---- ② ⚠⚠ **再减掉"同类边的全场中位"** ✗✗（**只留个性** ✓）—— 这一步不能省 ✗：
        #   不省的话，**多数框共有的残差**（波浪 / 配对误差 / 相机估计误差）会把主方向带跑 ✗
        #   —— 实测（帧 21 / 26 的主方向跑到 **101° / 191°** ✗ 就是被"多数框"带偏的 ✓）。
        #   ⇒ 这与轨迹判据 `dev = mv − median` 是**同一个口径** ✓（"**相对群体**"✓）。
        _sub = []
        for _eid in range(4):
            _v = [_x for _k, _x in _items if _k == _eid]
            _sub.append(float(np.median(_v)) if _v else 0.0)
        # ---- ③ 每条边投一票（按角度插值进 N 格 ✓ 权重 = 幅值 ÷ 噪声底 ✓）----
        for _k, _x in _items:
            _d = _x - _sub[_k]
            if abs(_d) < _DIR_VOTE_K * _noise:
                continue                                       # 太小 ⇒ 当噪声 ✓ 不投 ✗
            _ex, _ey = (_d, 0.0) if _k >= 2 else (0.0, _d)      # 左/右 ⇒ 横向；上/下 ⇒ 纵向 ✓
            _u = ((math.atan2(_ey, _ex) % (2.0 * math.pi)) / (2.0 * math.pi)) * self.dir_n
            _i0 = int(_u) % self.dir_n
            _i1 = (_i0 + 1) % self.dir_n
            _f = _u - int(_u)
            _wgt = abs(_d) / _noise
            _conf[_i0] += _wgt * (1.0 - _f)
            _conf[_i1] += _wgt * _f
        # ---- ④ ⭐ **跨拍平滑**（EMA ✓ 实测需要 ✓）—— 单拍投票会**抖** ✗：
        #   实测帧 18/19/20/22/24 的最亮方向都是 **281°（≈向上 ✓ 与用户口径一致 ✓）**，
        #   可**帧 21 / 23 就被"左右"那点噪声盖过去**了 ⇒ 跳到 11° / 101° ✗。
        #   ⇒ 平滑一下 ⇒ **主方向稳** ✓（⚠ 与"轨迹打分用 `dev` 中位"同理 ✓ 都是"别被单拍带走"✓）。
        if self._dir_ema is None or len(self._dir_ema) != self.dir_n:
            self._dir_ema = list(_conf)
        else:
            self._dir_ema = [0.6 * _a + 0.4 * _b for _a, _b in zip(self._dir_ema, _conf)]
        _sm = list(self._dir_ema)
        _pk = max(_sm) if _sm else 0.0
        # ⭐ **绝对强度** = 最强那一格相当于**几倍噪声底** ✓（⚠ 归一化后全是 1.00 ⇒ 看不出强弱 ✗）
        self.dir_strength = _pk / max(1.0, _noise)
        if _pk > 0.0:
            self.dir_conf = [min(1.0, _c / _pk) for _c in _sm]  # 归一化 0~1（最强的当 1 ✓）
            _k = max(range(self.dir_n), key=lambda _i: self.dir_conf[_i])
            self.dir_top = (360.0 * (_k + 0.5) / self.dir_n, self.dir_conf[_k])
        else:
            self.dir_conf = [0.0] * self.dir_n
            self.dir_top = None
        return self.dir_conf

    # ---------------- 主入口 ----------------
    def process(self, img, ts=None, dets=None):
        """喂一帧（+ 本拍 yolo 的框 ✓）⇒ `dict(pos, state, area, rad, vel, tracks, dev…)`。

        `dets` = `[(cls, cx, cy, w, h[, conf]), ...]`（**加工域** ✓ 与画面同一把尺 ✓）。
        """
        _dets = [b for b in (dets or []) if b is not None and len(b) >= 5]
        self.last_dets = len(_dets)
        # ⭐⭐⭐ **更新「一个目标有多大」**（全局标准面积 ✓ 见 `_AREA_WIN` ✓）——
        #   ⚠ 用**所有**框（不问真假 ✓）：因为**所有目标尺寸一样**（用户 2026-10-04 ✓ 硬先验 ✓）
        #     ⇒ 中位数就是"**单个目标的真实大小**" ✓（融合框只占少数 ✓ 晃不动中位 ✓）。
        for _b in _dets:
            self._area_hist.append(float(_b[3]) * float(_b[4]))
        if len(self._area_hist) > _AREA_WIN:
            del self._area_hist[:len(self._area_hist) - _AREA_WIN]
        if self._area_hist:
            self.std_area = float(np.median(self._area_hist))
        # ⚠ 没框 ⇒ 不观测（**照样走外推** ✓ 不是判丢 ✗ —— 用户第 ④ 条要"重合再分离后继续跟踪" ✓）
        _pairs = []
        if _dets and self.tracks:
            _pairs, _used_d = self._pair(_dets)
        else:
            _used_d = set()
        # ---- ① 位移 + ② 群体中位（⚠ 用"本拍观测 − 上一拍观测" ⇒ 与波浪无关的**相对**量 ✓）----
        _moves = {}
        for _tid, _j in _pairs:
            _t = self._by_id(_tid)
            _b = _dets[_j]
            # ⚠⚠ **一律换算成"每拍"** ✗✗（`÷ mv_span` ✓ 见 `_Track.mv_span` 那段 ✓）——
            #   这是"跨拍位移"那个真 bug 的修法 ✓；`span == 1`（绝大多数情况 ✓）时
            #   **一个数都不变** ✓ ⇒ 不会动到已经调好的行为 ✓。
            _sp = max(1, int(_t.mv_span))
            _moves[_tid] = ((float(_b[1]) - _t.prev[0]) / _sp,
                            (float(_b[2]) - _t.prev[1]) / _sp)
        _mx = _my = 0.0
        self._dev_med = 0.0
        self._cam_len = 0.0
        if len(_moves) >= _MIN_PAIRS:
            _mx = float(np.median([v[0] for v in _moves.values()]))
            _my = float(np.median([v[1] for v in _moves.values()]))
            # ⚠⚠ **`_cam_len` = "相机这一拍走了多少"** ✓ **它**不是**"偏离"** ✗✗ —— 原来我把
            #   这个值当成"**全场典型偏离**"显示给用户 ✗ ⇒ **日志在骗人** ✓（用户看到的
            #   "全场典型偏离 45.7 px" 其实就是 `hypot(median)` = **相机位移模长** ✓ 与"谁不合群"
            #   毫无关系 ✗）；真正的"典型偏离" = **各轨迹 `dev` 的中位** ✓ ⇒ 只能在下面轨迹循环
            #   结束后才算得出来 ✓（见 `_devs` ✓）。
            self._cam_len = float(np.hypot(_mx, _my))
            # ⭐ **相机速度的平滑值（EMA ✓）** —— ⚠⚠ **配对预测必须用它、不能用"本拍 median"** ✗✗
            #   （实测踩到 ✓ 自检 ②「波浪免疫」回归 ✗）：`median` 里**含着本拍的抖动** ✗
            #   （波浪/抖动是全场同步的 ⇒ 它会原样进 median ✓）⇒ 拿它当"下一拍相机走多少"，
            #   等于**把本拍的抖动当成相机速度** ✗ ⇒ 预测凭空多出一个**乱跳** ✗ ⇒ 配对变差 ✓。
            #   ⇒ 用 EMA 压掉抖动 ✓（相机本身是**缓速平滑**的 ✓ 用户第 ③ 条 ✓ ⇒ 平滑很安全 ✓）。
            self._med_ema = (_mx, _my) if self._med_ema is None else (
                0.5 * self._med_ema[0] + 0.5 * _mx,
                0.5 * self._med_ema[1] + 0.5 * _my)
            # ⭐⭐ **存下"群体中位位移"本身**（诊断 / 可视化要用 ✓ 用户："能看到判定的可视化依据" ✓）
            #   —— ⚠ 之前 `motion_viz` 里这个键填的是 `(0.0, 0.0)` 空值 ✗ ⇒ 用户看不到"相机这一拍
            #     走了多少" ⇒ **没法判断谁"不合群"** ✗（实测被用户一眼看出 ✓）。
            self._median_mv = (_mx, _my)
        # ---- ③④ 更新轨迹：偏离 ⇒ 累积（带衰减 ✓）----
        _updated = set()
        _devs = []          # ⭐ 本拍各轨迹的 `dev`（用来算**真正的**"全场典型偏离" ✓ 见下面 ✓）
        self._box_v = []                    # ⭐ 本拍重新收集（每个配对框一根蓝箭头 ✓ 见 `__init__`）
        for _tid, _j in _pairs:
            _t = self._by_id(_tid)
            if _t is None:
                continue
            _b = _dets[_j]
            # ⭐⭐⭐ **先判"这一拍它有没有跟别的目标粘住"** ✗✗（用户 2026-10-03 ✓ 关键线索 ✓
            #   见 `_STUCK_RATIO` 那段 ✓）—— 粘连时**框中心 = 两个目标的中点** ✗ ⇒ 这一拍的
            #   `mv` / `dev` 是**观测被拉偏的产物** ✗ **不能当"它在不合群"用** ✓✗。
            _area = float(_b[3]) * float(_b[4])
            # ⭐⭐⭐ **基准 = 全局「标准面积」** ✗✗（**不再用"这条轨迹自己学的 EMA"** ✓）——
            #   用户 2026-10-04 的硬先验："**所有目标尺寸一样**" ✓ ⇒ 那就该用**全局常量** ✓
            #   （见 `_AREA_WIN` ✓ 实测：面积倍数中位 **1.01** ✓ 90% 分位 1.29 ✓ 融合 >1.4x ✓）。
            #   ⚠ 好处：**新轨迹一出生就有正确基准** ✓ 而且**永远不用怕"基准被粘连顶上去"** ✓
            #     （那个"自欺陷阱"自动消失 ✓）。
            #   ⚠ 兜底：`std_area` 还没攒出来时（头几句框 ✓）用轨迹自己的 `area_ema` ✓ 不崩 ✓。
            _aratio = _area / max(1.0, float(self.std_area or _t.area_ema))
            if _aratio > self.stuck_ratio:
                _t.stuck += 1
                _t.cool = self.stuck_cool      # 粘连期把冷却**常置** ⇒ 分开后自然从它往回倒数 ✓
            else:
                _t.stuck = 0
                _t.cool = max(0, _t.cool - 1)  # ⭐ **分开之后再缓几拍**（见 `stuck_cool` ✓）
                # ⚠⚠ **只有"正常拍"才更新面积基准** ✗✗ —— 让粘连拍也更新的话，基准会被粘连
                #   自己顶上去 ⇒ 下一拍就"看起来正常"⇒ **永远检测不出来** ✓（自欺陷阱 ✓）。
                _t.area_ema = (1.0 - _STUCK_EMA) * _t.area_ema + _STUCK_EMA * _area
            # ⚠⚠⚠⚠ **粘连 / 冷却拍：整条观测链一律"不采信这个框"** ✗✗✗（**帧 13~16 病根的根治** ✓）
            #   用户 2026-10-03 给的时间线 ✓（我逐帧量过 ✓）：真目标**朝左上**穿过两个假目标
            #   ⇒ 帧 13/14 与**下方**那个粘连（框 157×207 / 179×208 ✓）、帧 15 与**上方**那个接触、
            #   帧 16 与**上方**那个重合（183×209 ✓）✓。
            #   ⚠⚠ **病根**：粘连期它的 `obs` **正好等于融合大框的中心**（实测帧 13 `obs=(354,311)`
            #     = 大框中心 ✓ 帧 14 `obs=(360,323)` ✓ 一模一样 ✓）⇒ 这一个"中点"**同时污染了
            #     三样东西** ✗：① `obs` 本身（位置被拽到下方假目标那边 ✓）② `vel`（拿到 +11/+8 的
            #     "往下"假速度 ✓）③ `rel` / KF（喂进去的是"中点"⇒ `vr` 也被带偏 ✓）⇒ **粘连一结束
            #     它就沿这条假速度一路右下，再没回来** ✗✗（实测：帧 15~21 从 (388,368) 走到
            #     (399,449) ✗ 而真目标在 (302,221)→(310,284) 的**左上** ✓ 方向完全相反 ✓）。
            #   ⇒ 所以**光"降权"不够** ✗（那只压住了报出去的 `pos` ✓ 观测链全没保护 ✓）——
            #     现在**整条链都跳过**：① `mv`/`dev` 记 0（"这拍它没个性运动"✓）② `rel` 不累
            #     ③ `box_v` 不出 ④ `obs` = **上一拍算好的预测**（= 沿轨迹滑 ✓ 正是用户说的
            #     "**沿着轨迹预测**"✓）⑤ KF **只 predict、不 update** ✓（不喂这个被污染的点 ✓）
            #     ⑥ `vel` 不更新（保住"进粘连前"的速度 ✓）。
            _stuck_now = bool(_t.stuck or _t.cool)
            _dev = (0.0 if _stuck_now else
                    (math.hypot(_moves[_tid][0] - _mx, _moves[_tid][1] - _my)
                     if len(_moves) >= _MIN_PAIRS else 0.0))
            _t.mv = ((0.0, 0.0) if _stuck_now else _moves[_tid])
            _t.dev = _dev                          # ⭐ 本拍偏离（**记原值** ✓ 诊断/可视化要看真值 ✓）
            if len(_moves) >= _MIN_PAIRS and not _stuck_now:
                _devs.append(_dev)                 # ⚠ 粘连期**不进噪声底** ✗（否则噪声底被抬 ✓）
            # ⭐⭐⭐ **打分用的是 `dev` 的"最近几拍中位"** ✗✗（**不是单拍** ✓ 见 `_DEV_WIN` ✓）——
            #   ⚠ 实测（帧 19）：**单拍** 69.7 的尖峰一下把分数从 58 顶到 116 ⇒ **立刻换错人** ✗；
            #     取 3 拍中位之后，**尖峰一抹就掉** ✓ 而"**持续**偏离"（真信号 ✓）照样过得去 ✓。
            #   ⚠ `dev_hist` 只在**没粘住**时更新 ✗（粘连期 `dev` 记的是 0 ✓ 混进去会**稀释**真信号 ✓）。
            if not _stuck_now:
                _t.dev_hist.append(_dev)
                if len(_t.dev_hist) > _DEV_WIN:
                    _t.dev_hist.pop(0)
            # ⚠⚠ **粘连 / 冷却期：有效 `dev` 一律记 0** ✗✗ —— 否则会**拿"粘住之前那几个老值"**
            #   来打分 ✗（实测：窗口里还留着 `[30,30,30]` ⇒ 中位 30 ⇒ **照样把分顶上去** ✗✗
            #   自检 `test_stuck_deprioritize` 当场抓出来 ✓）⇒ 粘连期就该是"**这一拍它没表现出
            #   任何个性运动**" ✓（打分不奖不罚 ✓）。
            _dev_eff = 0.0 if _stuck_now else (
                float(np.median(_t.dev_hist)) if _t.dev_hist else _dev)
            # ⭐⭐ **"相对群体"的累计**（用户要的那条轨迹线 ✓ 见 `_Track.rel` 说明 ✓）：
            #   本拍它净走了 `mv − median` ⇒ 累到 `rel` 上 ⇒ 得到"它相对大家走到了哪" ✓。
            #   ⚠⚠ **粘连期一律不动** ✗✗（那条线靠 `mv − median` 累 ✓ 而粘连期的 `mv` 是"中点位移"
            #     ✗ ⇒ 累进去 ⇒ **线被拽跑** ✓ 实测帧 13/14 它就是这么被带偏的 ✓）。
            if _stuck_now:
                # ⚠⚠ **粘连 / 冷却期：`rel` 也要"跟着它走"** ✗✗（用户 2026-10-04 ✓ 原话："为什么
                #   第 15 帧**橙色轨迹线不跟了**" ✓）—— 原来这段是**完全不动** ✗ ⇒ 那条线**停住
                #   不长** ✓ 看着像"断了" ✗（而它其实每拍还在补点 ✓ 只是形状不变 ✓）。
                #   ⇒ 而我们的**位置**在粘连期本来就是**沿 `vr`（它自己的相对速度）滑**的 ✓
                #     ⇒ 那 `rel` 就该**推进同样的量** ✓✓ ⇒ **两者同源、不自相矛盾** ✓
                #     （⚠ 用**上一拍那份没被污染的 `vr`** ✓ —— 本拍的 `vr` 要等下面才更新 ✓）。
                _t.rel = (_t.rel[0] + _t.vr[0], _t.rel[1] + _t.vr[1])
            else:
                _t.rel = (_t.rel[0] + _moves[_tid][0] - _mx,
                          _t.rel[1] + _moves[_tid][1] - _my)
            _t.rel_hist.append(_t.rel)
            if len(_t.rel_hist) > _REL_HIST:       # 只留最近 `_REL_HIST` 点（省内存 + 画面清爽 ✓）
                _t.rel_hist.pop(0)
            # ⚠⚠ **`score` 只用"可信的 `dev`"** ✗✗（= 用户原话"**别急于寻找跟踪信号**" → 更进一步：
            #   干脆**不采信** ✓）—— 粘连期那个"偏离"（实测帧 13 的 **40.5** ✗）是**观测被粘住的
            #   产物** ✗ 不是目标的个性运动 ✓ ⇒ 拿它加分 = **把假信号当成"最不合群"** ✗✗
            #   （旧代码正是这么干的 ⇒ `#13` 的 `score` 帧 13 涨到 198.6 ✓ **越粘越像目标** ✗）。
            _t.score = _t.score * self.score_decay + _dev_eff
            # ⭐ **收一根"本框的瞬时速度"**（用户要的蓝箭头 ✓ 见 `_box_v` 说明 ✓）
            #   ⚠ 粘连期**不出**（那根箭头画的是"中点怎么挪"✗ 假的 ✓ 会骗人 ✓）。
