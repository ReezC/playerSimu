class _KF2D:
    """**匀速卡尔曼**（在 **"相对群体"坐标**里跑 ✓）—— 给每条轨迹的 **预测 / 平滑速度 / 新息** ✓。

    ⚠⚠ **坐标选对了，KF 才成立**（这是本类存在的唯一理由 ✓ 不是"为了 KF 而 KF" ✗）：
      · 用户 2026-10-03 原话："其实我们的这个目标**变速是很均匀的、不会发生跳变**，基于 KF 的
        **平滑运动曲线观测**好像也能取得比较客观的效果" ✓ ⇒ **实测支持** ✓：
        帧 1~12（**有白星真值**的那段 ✓）真目标"相对群体"速度 ≈ **22 px/拍**、每拍变化只有
        **5.6** ⇒ **加速度 / 速度 = 0.25** ✓✓ ⇒ **匀速模型在这里成立** ✓（不是硬套 ✓）。
      · 但**在绝对坐标里不成立** ✗：相机每拍就走 **20+px** ✓（实测峰 45px）而目标的相对速度
        才 22px ✓ ⇒ 绝对坐标里的运动是"相机大位移 + 目标小运动"✗ ⇒ 匀速假设被相机**整个带偏** ✗；
      · ⇒ **减掉"累积群体位移"之后**（= `_Track.rel` 那套 ✓）：**假目标基本不动**（只剩噪声 ✓）、
        **真目标匀速移动** ✓ ⇒ 这才是 KF **名正言顺**的地方 ✓✓
        （⚠ 而这**恰好**也是本模块判据免疫波浪的原因 ✓ 同一件事 ✓）。
    ⚠ **务实地说收益在哪** ✓（别夸大 ✓）：① 配对用它的**预测位置**（比"上一拍观测"抗抢框 ✓）；
      ② `vel` 用它（比一阶滤波干净 ✓）；③ `innovation`（观测 − 预测）可当**异常度**看 ✓
      —— ⚠ 它**不能**替我们回答"哪个框是真目标"✗（那是判据 + 关联的事 ✓）。
    """

    __slots__ = ("x", "P", "q", "r")

    def __init__(self, q=_KF_Q, r=_KF_R):
        self.x = np.zeros(4, float)          # `[rx, ry, vx, vy]` ⇒ **相对位移 + 相对速度**
        self.P = np.eye(4) * _KF_P0
        self.q = float(q)
        self.r = float(r)

    def predict(self, dt=1.0):
        _f = np.array([[1, 0, dt, 0], [0, 1, 0, dt], [0, 0, 1, 0], [0, 0, 0, 1]], float)
        self.x = _f @ self.x
        _q = np.diag([self.q * dt ** 4 / 4.0, self.q * dt ** 4 / 4.0,
                      self.q * dt * dt, self.q * dt * dt])
        self.P = _f @ self.P @ _f.T + _q
        return self.x[:2]

    def update(self, zx, zy):
        """喂本拍的**相对位移** ⇒ 回**新息**（= 预测差了多少 ✓ 可当异常度看 ✓）。"""
        _h = np.array([[1, 0, 0, 0], [0, 1, 0, 0]], float)
        _y = np.array([float(zx), float(zy)]) - _h @ self.x        # ⭐ 新息
        _s = _h @ self.P @ _h.T + np.eye(2) * self.r
        _k = self.P @ _h.T @ np.linalg.inv(_s)
        self.x = self.x + _k @ _y
        self.P = (np.eye(4) - _k @ _h) @ self.P
        return float(np.hypot(_y[0], _y[1]))

    def damp(self, d):
        """没观测那几拍：**只让速度柔和衰减** ✓（别带着虚高的速度冲出去 ✓）。"""
        self.x[2] *= d
        self.x[3] *= d
        return self.x[:2]


