        #     就是 `obs` ✓）；
        #   · 每拍 `rel += (自身位移 − 群体中位位移)` ✓ ⇒ **它"相对大家"净走了多少** ✓；
        #   · `rel_hist` = 这条线的最近若干点 ✓（画到画面上就是**"相对群体的轨迹线"** ✓✓）。
        #   ⭐ **为什么这条线一眼能分辨真假** ✓：把"大家一起动的那一份"减掉之后 ——
        #     **假目标** ⇒ 残余只是噪声 ⇒ 线**绕着原地打转** ✓；
        #     **真目标** ⇒ 残余是它自己的运动 ⇒ 线**朝一个方向持续延伸** ✓✓。
        self.rel = (float(cx), float(cy))
        self.rel_hist = [(float(cx), float(cy))]
