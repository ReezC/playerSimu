    def _climb_step(self, now, px, py, _on_ladder, _in_src,
                    climb_failed=False, climb_stalled=False):
        """② 上绳 / 「还没上绳」那一大段（`_on_ladder`、`_in_src` 由 `update` 算好传入 ✓）。"""
        # 还没上绳 / 中途掉下来：**给一段容错期**再判失败 —— 按跳那几拍人本来就还在
        # 空中（`ladder_id` 是 None），一离开就判失败会当场误杀。
        # ⚠ 但**站在起跳平台上**不算"在空中"（见下面 ②' 那段）✓
        if _on_ladder:
            # ⚠ 判据必须**和上面同一份**（`_on_ladder` ✓，含那条"位置兜底" ✓）——
            #   以前这里直接看原始参数 `ladder_id` ✗ ⇒ 兜底不生效、"点按重试"那几拍还是会
            #   走进下面"还没上绳"那一支 ⇒ 又松开 ↑ ⇒ 原地打转 ✗（用户 2026-09-27 报的 ✓）。
            self._off_since = None
            self._dir_tap_at = None
            self._retry_stage = ""     # 人已经在绳上了 ⇒ "等 y 稳定/点按"那一小段收干净 ✓
            if self._mid_arm_since is None:
                self._mid_arm_since = now   # ⭐ 上爬"在绳上"从这一刻算（`MID_ARM_S` 门槛 ✓）
            # ---- **下爬（dir < 0）：另一套收尾**（2026-09-26 用户定的新时序）----
            # 用户原话：「判定上绳梯后，经过『坐标对齐误差时间』，松开 ↓ 并执行一个
            # '跳下绳梯' 的操作行为：按住目标 foothold 集合的中心对应的方向键（向量运算
            # 就能解决）→ 按跳 → 松开跳 → 松开方向 → 等待 y 稳定」。
            # 为什么下爬**不再沿绳降到绳底**：绳只是个"把人从平台面上放下去"的抓手 ——
            # 抓住绳时人已经在平台面**下面**了（实测 105090600 的 L1：绳顶 y=-205、平台面
            # y=-208 ⇒ 人比平台面低 3px），松手就是往下落 ✓；按住"朝目标集合中心"的方向
            # 是为了**落点漂到平台中间**（绳常常正挂在平台边上）。
            # ⚠ 下面那条「爬不动了」**只对向上爬有效**（它的前提就是用户说的"在绳上、
            #   不偏离、↑ 没松就一定能上去"）；下爬在绳上只待 hold_ms，不走那段 ✓。
            if self.dir < 0:
                if self._on_ladder_since is None:
                    self._on_ladder_since = now
                    self.note = ("已上绳：按住 ↓ 稳 %d ms 再松手跳下（朝目标集合中心）"
                                 % self.hold_ms)
                    if self.hold_ms > 0:
                        return self._out(0, False, hold_dir=True)
                elif (now - self._on_ladder_since) * 1000.0 < self.hold_ms:
                    return self._out(0, False, hold_dir=True)   # 稳住，↓ 还按着
                self.phase = self.JUMP_DOWN
                self.note = "松 ↓，跳下绳梯"
                return self._jump_down_beat(now, px)
            # ⭐⭐ **「中途跳下」触发点**（用户 2026-09-28 ✓）：**已经在绳上往上爬**的时候，
            #   爬到「高度」就转去"跳下来"（见 `MID_JUMP` 相 ✓）。
            #
            # ⚠⚠ **判据方向 2026-09-28 改过**（用户："把右下爬跳到左上 A+B 也修掉"✓）：
            #   现在是 **`py <= mid_y`** = "**人的 y 已经爬到「高度」或更高**" ✓
            #   （世界 y **越小越靠上** ✓）。原来是 `py >= mid_y` ✗ ⇒ 那是"人还在该高度的
            #   **下方**" ⇒ **一上绳（y 最大）就满足** ⇒ 当场触发、还把 `_mid_jumped` 锁死
            #   ⇒ 之后**一路爬到顶也不跳** ✗（用户报的"**他爬到顶了都没跳出去**"✓）。
            #   ⚠ **为什么配 50 是合理的**：真实数据 L2 是 `y1=-115(上端) … y2=231(下端)`
            #     ⇒ 50 落在绳的**中上段** ⇒ "爬到那儿再往左跳"正是用户要的 ✓（原来那句
            #     "配大了就等于上去就跳"是**错的**，真相反过来 ✓）。
            #
            # ⚠⚠ **门槛 `MID_ARM_S`**（同一轮加 ✓）：必须**已经在绳上稳了一小会儿**才判 ——
            #   刚"吸上绳/跳上绳"的那一瞬间 `_on_ladder` 就为真、`py` 又常常刚好满足条件
            #   ⇒ 会在**还没真开始爬**的时候就把 `_mid_jumped` 用掉 ✗（防抖 ✓）。
            #   ⚠ 起点用**独立字段** `_mid_arm_since`（**不动** `_on_ladder_since` —— 那个是
            #     下爬分支专用的计时起点，混用会改掉下爬的"稳住 hold_ms"行为 ✗）。
            # ⚠ **只触发一次**（`_mid_jumped` ✓）：跳下来之后人可能会再贴到绳上，不加这道锁
            #   就会"上去了又跳"来回抖 ✗。
            # ⚠ 放在**下爬分支之后**：下爬有它自己那套收尾，别掺和 ✗。
            if (self.dir > 0 and not self._mid_jumped and self.mid_dir
                    and self.mid_y is not None and py is not None
                    and float(py) <= self.mid_y
                    and self._mid_arm_since is not None
                    and (now - self._mid_arm_since) >= MID_ARM_S):
                self._mid_jumped = True
                self.phase = self.MID_JUMP
                self.note = ("爬到中途：y=%.0f 已到「高度」%.0f ⇒ 跳下绳梯（向%s），↑ 不松"
                             % (float(py), self.mid_y,
                                {"center": "目标中心", "left": "左", "right": "右"}
                                .get(self.mid_dir, self.mid_dir)))
                return self._mid_jump_beat(now, px)
            # ⭐ 向上爬**只认广播**（用户 2026-09-28 核心思路：**位置状态机全权掌握坐标→状态的
            #   解析，执行器只负责发键和通知，不做任何坐标运算判定** ✓）：
            #   · 2a `climb_failed`（x 偏出「坐标对齐误差范围」）⇒ 攀爬失败 → 交给 agent 延迟重启；
            #   · 2c `climb_stalled`（y 在「移动操作尝试间隔」内没变）⇒ 补发按住 ↑（`reassert` ✓）；
            #   · 2b `at_ladder_top` 已由 `_arrive_step` 判（到顶收工 ✓）。
            #   ⚠ 原来这里自己比 y（`_stalled_by` / `_best_y` / `_best_at` / `_reassert_at` /
            #     `reassert_s` 那一套）**全删** ✗ —— 那是执行器做坐标判定的最后一处 ✗。
            if climb_failed:
                return self._fail("攀爬失败：x 偏出「坐标对齐误差范围」（位置状态广播）")
            if climb_stalled:
                return self._out(0, False, hold_dir=True, reassert=True)
            # **已经上绳 ⇒ 只按方向键（↑），不再按跳**（用户 2026-09-26 定的规则：
            # "按 ↑ 直到玩家的真实世界坐标 ≤ 绳梯上端连接的 foothold 的 y"）。
            # 跳键**只用来贴上绳**：一直按住它，人会卡在绳上/绳顶不往上走
            #（用户实测：命令前往左上平台时"还在绳上、离平台还差一截"）。
            # 注意这里要 `hold_dir`：不按跳也得把 ↑ 按住，否则这一拍什么都不按=站着不动。
            # ⚠ 目标取 `_target_y()`（上爬 = 绳上端、下爬 = 落地面）—— 别在这儿再写一遍
            #   "目标是谁"，否则改口径时提示会和判据对不上（见 `_target_y` 的说明）。
            self.note = "已上绳：按住 %s 往上爬（到 y ≤ %.0f 算到）" % (
                "↑" if self.dir > 0 else "↓", self._target_y())
            return self._out(0, False, hold_dir=True)
        # ⚠ 人**不在绳上** ⇒ 「在绳上稳了多久」的起点清掉（下一回上绳必须重新攒够门槛 ✓）
        self._mid_arm_since = None
        # ---- ②' 还没上绳、人**还站在起跳那块平台上** ----
        # 用户 2026-09-27 定的流程（这一版）：对齐 x → 按跳 + 按住 ↑ → **如果还没上绳
        # （人还在起跳那块 foothold 集合里）⇒ 回到对齐 x 重新开始**（整个流程重来一遍）。
        # 所以一轮只按**一下**跳（点按，不是按住：跳键按住在游戏里只算"按过一次"，
        # 本机 `KeyState` 也只在键集**变化**时才发键 ⇒ 一直 True 等于只发过一次 ✗），
        # 下一拍就退回 ALIGN 重走 —— 于是**两次尝试之间的间隔 = ① 那个保持窗口**
        # （`hold_ms` = 设置里的「坐标对齐误差时间」+ 端到端延迟 ✓，不新造常数 ✓）。
        # ⚠ 站地上**不算"掉下来了"**（不记 `_off_since`），否则 2 秒就开始判失败、
        #   和"重来"这条直接打架 ✗；真掉下来（离开那块平台、又不在绳上）那条路照旧 ✓。
        # ⚠ 重来那一轮里**方向键继续按着**（`_retrying`）：用户原话"按跳 + 按住 ↑" ——
        #   中间松手，人在空中那一下就抓不住绳 ✗（抓上了会自动接"已在绳上"那条 ✓）。
        # ⚠ 退回对齐**之前**还补一次**目标方向（↑/↓）的点按**（用户 2026-09-27 要求）：
        #   "先松 `TAP_PERIOD_S - TAP_ON_S`、再按 `TAP_ON_S`" —— 因为按跳那一拍 ↑/↓ 是
        #   按着的，不松开再按就不算"新的一次按下" ✗（见 `_dir_tap_at` 那一段）。
        if _in_src:
            self._off_since = None
            # ---- ③ 跳失败之后的**两件前置事**（用户 2026-09-27 要求）----
            #   ① **先站住等 y 稳定**：刚跳失败时人可能还在空中往下落，那个当口按方向键
            #      会把他挪歪 ✗ ⇒ 这几拍**什么键都不按**，等 y 不再变了再往下走。
            #      "稳定"用的是同一套 `_y_settled` ✓，但时长是**内置的 `RETRY_SETTLE_S`=1s**
            #      （用户 2026-09-27 明确："跳失败后到调整的间隔用这个时间太长了"✗ ——
            #      这里要快节奏，**不跟**设置里那格「卡住判定时长(s)」走 ✓）。
            #   ② **再补按一次目标方向**：⚠ **上爬没有"点按 ↑"**（用户 2026-09-27 更正："向上
            #      攀爬只有「按住 ↑」和「补按住 ↑」，不能存在「松开 ↑」和「点按 ↑」"）⇒ 上爬
            #      是"**按住 ↑ + `reassert`**"（只再发一次 PRESS ✓ 不先松 ✓，见 `_retry_all_up`）；
            #      **下爬**才走老的"先松再按"（`TAP_PERIOD_S - TAP_ON_S` + `TAP_ON_S` ✓）。
            # 两件都做完才回 ① 对齐 x ⇒ **后续的跳**自然排在"稳定 + 点按 + 对齐"之后 ✓。
            if self._retry_stage == "y":
                if not self._y_settled(now, py, still_s=RETRY_SETTLE_S):
                    self.note = ("还没上绳（还站在 %s 上）⇒ **先站住等 y 稳定**"
                                 "（刚跳失败，人可能还在落：%.0f px 内静 %.0f s 算稳）"
                                 % (self.src_set, STALL_GAIN_PX, RETRY_SETTLE_S))
                    # 站住：**别横着挪**、别按跳 ✓ —— ⚠ 上爬这一拍 `dir` 仍会被 `_out` 补成 ↑ ✓
                    #（用户 2026-09-27："向上攀爬只有「按住 ↑」和「补按住 ↑」"✓）
                    return self._out(0, False)
                self._retry_stage = "tap"                 # y 稳了 ⇒ 接着走点按 ✓
            if self._retry_stage == "tap":
                # ⭐ **上爬没有"点按 ↑"**（用户 2026-09-27 明确："向上攀爬只有「按住 ↑」和
                #   「补按住 ↑」，**不能存在「松开 ↑」和「点按 ↑」**"）⇒ 上爬这一小段 =
                #   **按住 ↑ + 补按一次**（`reassert=True` = 只再发一次 PRESS ✓，绝不先松开 ✓），
                #   然后回对齐重走一遍 ✓ —— 见 `_retry_all_up` ✓。
                if self.dir > 0:
                    return self._retry_all_up(now)
                # ---- 下爬：走老逻辑（**先松再按**才算"新的一次按下"✓，见 `_dir_tap_at` 的说明）。
                #      为什么它能"先松"：那几拍人已经**主动离开绳**（"跳下绳梯"那一相 ✓）⇒
                #      松 ↓ 是语义本身 ✓，和上爬"不能松开 ↑"不冲突 ✓。
                #      按跳那一拍 ↓ 本来是**按着**的 ⇒ 不松开再按，对面只看到"一直按着" =
                #      **一次都没新按过** ✗ ⇒ 那一下白按 ✗；补一下就是"再试着直接抓一次绳" ✓。
                if self._dir_tap_at is None:
                    self._dir_tap_at = now
                    self.note = ("还没上绳（还站在 %s 上）⇒ 先松开 ↓ 再点按一次"
                                 "（要「松开再按」才算新的一次）" % self.src_set)
                    return self._out(0, False)            # dir=0 ⇒ 把 ↓ 松开
                _tap_dt = float(now) - self._dir_tap_at
                if _tap_dt < TAP_PERIOD_S - TAP_ON_S:
                    self.note = "还没上绳 ⇒ 再松 %.0f ms（松够了才好「重新按一次」）" % (
                        (TAP_PERIOD_S - TAP_ON_S - _tap_dt) * 1000.0)
                    return self._out(0, False)            # 松开中，别急
                if _tap_dt < TAP_PERIOD_S:
                    self.note = ("还没上绳（还站在 %s 上）⇒ **点按一次 ↓**"
                                 "（再试着直接抓绳）" % self.src_set)
                    return self._out(0, False, hold_dir=True)   # 这一拍才算"新按下"的 ✓
                return self._retry_back_to_align("点按过 ↓")
            if not self._jump_tried:
                # ⚠ 这里原来也有一道"按跳许可"（`_at_entry` ✓）—— 2026-09-27 用户明确否掉
                #   （"**对齐了就按跳开始爬啊，不需要判定别的**" ✓）⇒ **一起拆了** ✓。
                #   这一相里人可能已被挤走 / 被打飞 ⇒ 那交给"跳了没上去 ⇒ 回对齐重来"
                #   那一小段（就在下面 ✓）判，不再用 y 位置在按跳前拦 ✗。
                self._jump_tried = True
                self.note = "还没上绳（还站在 %s 上）⇒ 按跳 + 按住 %s" % (
                    self.src_set, "↑" if self.dir > 0 else "↓")
                return self._out(0, True)                 # 按跳 + 按住方向
            # ---- 跳也按过了、人**还在起跳平台上**（跳没生效 / 又落回来了）⇒
            #      进入"重来"那一小段：**先等 y 稳定**（见本段开头 ⚠）----
            self._retry_stage = "y"
            self._jump_tried = False
            self._y_ref = None                # 从这一拍开始量"y 动没动"（`_y_settled` 的锚点 ✓）
            self._y_still_since = None
            self.note = ("还没上绳（还站在 %s 上）⇒ 先站住等 y 稳定"
                         "（刚跳失败，人可能还在落）" % self.src_set)
            # 站住别横挪 / 别按跳 ✓（上爬这拍的 ↑ 由 `_out` 补上 ✓）
            return self._out(0, False)
        if self._off_since is None:
            self._off_since = now
        elif (now - self._off_since) >= OFF_LADDER_GRACE_S:
            return self._fail("从 %s 上掉下来了（%.0fs 没回到绳上）" % (
                self.ladder_id, OFF_LADDER_GRACE_S))
        # 不知道起点集合（手工建的任务 / 老调用方）⇒ 退回老行为：一直按住跳
        return self._out(0, True)

    def _arrive_step(self, now, px, py, here_sets, at_top, at_bottom, ground_y,
                     on_rope):
        """到达 / 「跳下绳梯」相（`None` = 还没到，落到 CLIMB ✓）。"""
        if self._arrived_at is not None:
            # ⚠ 这里**只有向上爬**会走到（下爬在判到到达那一拍就直接收工了，见下面那段），
            # 所以"到达后再按住一会儿"只是 ↑ 的语义（用户 2026-09-26：↑ 要延迟『坐标对齐
            # 误差时间』再松）。2026-09-28 用户重新审视：**时长用纯「坐标对齐误差时间」**
            # （`base_hold_ms`，不含端到端延迟 ✓）—— 理由是**游戏机制**（"迈上平台"那一步
            # 要按着 ↑），跟读数延迟无关；端到端延迟只补偿在「对齐稳住」那边（对齐依赖读数 ✓）。
            if (now - self._arrived_at) * 1000.0 < self._arrived_hold:
                return self._out(0, False, hold_dir=True)
            self.phase = self.DONE
            self.note = self._arrived_why
            return self._out(0, False)

        # ---- 下爬的「跳下绳梯」相：**落地**的几个判据（见 `_landed`）----
        # ⚠ 必须排在下面"不在绳上 ⇒ 判掉下来了"那条**之前**：这一相是**主动**离开绳子的
        #   （按住左右方向键在游戏里就是松手），`ladder_id` 当然是 None —— 拿它当"掉下来了"
        #   会在 OFF_LADDER_GRACE_S 之后把刚跳下去的人判成失败 ✗。
        if self.phase == self.JUMP_DOWN:
            _why = self._landed(now, py, here_sets, at_bottom=at_bottom,
                                ground_y=ground_y, on_rope=on_rope)
            if _why:
                self.phase = self.DONE
                self.note = _why
                return self._out(0, False)      # 落地即松手（方向键也一起松）
            return self._jump_down_beat(now, px)
        # ---- ⭐ 「中途跳下」（**上爬**中途，用户 2026-09-28 ✓）----
        # ⚠ 与 `JUMP_DOWN` **同一个理由**必须排在"不在绳上 ⇒ 判掉下来了"那条**之前** ✗：
        #   这一相本来就是**主动**离开绳（跳下来 ✓）⇒ `ladder_id` 当然没了 ⇒ 拿它判"掉下来了"
        #   会在 OFF_LADDER_GRACE_S 之后把刚跳下的人判成**失败** ✗（同下爬那条注释 ✓）。
        if self.phase == self.MID_JUMP:
            if self._mid_land_at is None:
                _why = self._mid_landed(now, py, on_rope)
                if _why is None:
                    return self._mid_jump_beat(now, px)      # 还在落 ⇒ 走那一相的时序 ✓
                self._mid_land_at = now                      # = 用户说的"**返回成功**"那一刻 ✓
                self.note = _why + "（↑ 再按住 %.0f ms 才松）" % (self.mid_hold_s * 1000.0)
                return self._out(0, False, hold_dir=True)    # ⚠ **先不松 ↑** ✓
            # ⭐ 落地之后**再按住 ↑ `mid_hold_s`** 才松（用户原话："直到**返回成功或失败后**
            #   再经过「**移动操作尝试间隔**」松开"✓）
            if (now - self._mid_land_at) < self.mid_hold_s:
                return self._out(0, False, hold_dir=True)    # ⚠ 还是不松 ↑ ✓
            self.phase = self.DONE
            self.note = ("中途跳下：已落地、↑ 又按住 %.0f ms ⇒ 收工"
                         % (self.mid_hold_s * 1000.0))
            return self._out(0, False)                       # 到这里才真松（方向与 ↑ 一起 ✓）
        why = self._arrived(py, here_sets, at_top,
                            at_bottom=at_bottom, ground_y=ground_y)
        if why:
            self._arrived_at = now
            self._arrived_why = why
            # ⚠ 不能 `max(1, …)`：误差时间设成 0 = **要立刻松手**（老行为），
            # 硬留 1 ms 会让"这一拍就该收工"的用例（和用户自己设 0 的情况）卡住 ✗。
            # ⭐ 用**纯的**「坐标对齐误差时间」（`base_hold_ms`），不是被端到端延迟加长后的
            #   `hold_ms`（那个是给「对齐稳住」用的 ✓）—— 用户 2026-09-28 重新审视 ✓。
            self._arrived_hold = max(0, int(self.base_hold_ms))
            # ⚠ **下爬（dir < 0）没有"再按住一会儿"这一步**（2026-09-26 用户定的新时序）：
            # 下爬的到达发生在「跳下绳梯」**落地**那一刻，落地后再按住水平方向键 hold_ms
            # 会顺着平台走出去 ✗（用户口径："方向键按住到 y 稳定为止"⇒ 落地就松手）。
            # ⇒ 直接收工；`_arrived_at` 不会被置上，上面那段"再按住"就只剩 ↑ 会走 ✓。
            if self.dir < 0 or self._arrived_hold <= 0:
                self.phase = self.DONE
                self.note = why
                return self._out(0, False)
            self.note = ("%s（再按住 ↑ %d ms 再松）" % (why, self._arrived_hold))
            return self._out(0, False, hold_dir=True)

        return None

    def _align_step(self, now, px, py, _on_ladder):
        """① 对齐相：斜跳 / 横向对齐 / 按跳（`None` = 对齐好了，落到下一段 ✓）。"""
        # ---- ①'' **斜跳飞行中：朝绳走 + 按住 ↑**（用户 2026-09-27 现场）----
        # 原话："现在斜跳上绳梯会有「**经过绳梯却没有上去**」的现象，**空中吸附绳梯的
        #   条件是「正在按住 ↑」**"。
        # 为什么单开这一段：斜跳是"按住朝向 + 跳"跳出去的 ✓，但**跳完那一拍**开始就走回
        #   下面的对齐逻辑了 —— 它每拍发的是"**只按水平方向**"（`_out(sign, False)`
        #   ⇒ `dir=0`）✗ ⇒ **↑ 被松开** ⇒ 人从绳梯旁边飞过去**吸不上** ✗。
        # 所以飞行期间：朝绳走（`move=sign`）+ **按住 ↑**（`vert=1`）、**不再按跳**（一轮一次 ✓）。
        # ⚠ 一律按 **↑**（不是 ↓）：用户给的条件就是"空中吸附绳梯要按住 ↑" ✓ —— 下爬开局
        #   吸上绳也一样，吸上之后才由 CLIMB 相按 ↓ 往下走 ✓。
        # ⚠ 结束只有两条路：吸上绳 ✓ / **落回起跳高度**（其间必须**离开过**一个「坐标对齐
        #   误差范围」，否则刚起跳那几拍就自己结束了 ✗）⇒ 之后交回下面的老逻辑 ✓。
        if self._diag_flying:
            if _on_ladder:
                self._diag_flying = False        # 吸上了 ⇒ 下面"已在绳上"那支接管 ✓
            elif py is not None:
                if self._diag_y0 is None:
                    self._diag_y0 = float(py)
                if abs(float(py) - self._diag_y0) > self.tol_px:
                    self._diag_left = True
                elif self._diag_left:
                    self._diag_flying = False    # 落回起跳高度 ⇒ 这一跳结束 ✓
            # ⚠ **兜底**：飞行相**总时长**超过「卡住判定时长」⇒ 这一跳**无论吸没吸上、落没落回
            #   起跳高度**都结束，交回下面的老逻辑 ✓（不新造时长：用的就是攀爬那件
            #   「卡住判定时长」✓）。
            #   ⛔ 2026-09-28 修：原来只兜"**没离开过**起跳高度"（`not self._diag_left`）✗ ——
            #   那是给"这一跳根本没飞起来"兜的；可人一旦**离开过**起跳高度（`_diag_left=True`）
            #   而**既没吸上绳、也没落回起跳高度**（斜跳落到了绳旁另一个高度 / 或挂在绳上广播
            #   还没判"在绳上"）⇒ 兜底失效 ⇒ **永远卡在飞行相** ✗（用户 2026-09-28 报
            #   "一楼到二楼又出问题、斜跳飞行会卡" ✗）。所以改成**只看总时长** ✓。
            if (self._diag_flying and self._diag_at is not None
                    and (float(now) - self._diag_at) >= self.stall_s):
                self._diag_flying = False
            if self._diag_flying:
                _dxf = self.x - float(px)
                _sgf = 1 if _dxf > 0 else (-1 if _dxf < 0 else 0)
                self.note = ("斜跳飞行中：朝绳%s + **按住 ↑**"
                             "（空中吸绳要 ↑ 一直按着，跳不再按 ✓）"
                             % ("→" if _sgf > 0 else ("←" if _sgf < 0 else "（已对上）")))
                return self._out(_sgf, False, vert=1)

        dx = self.x - float(px)
        # ⭐ **斜跳第 2 拍**（上一拍已经发过"朝绳走" ⇒ 这一拍**才按跳** ✓，见下面第 1 拍那段）——
        #   ⚠ 放在 `|dx| > tol` 判断**之前**：朝绳走了一步可能就进容差了，那一拍**照样要跳** ✓
        #   （这一轮的目的就是跳上去 ✓）。`_out` 里按了跳会清 `_align_pressed` ⇒ 下一轮又要点 ✓。
        if self._diag_arming is not None:
            _sgn = 1 if dx > 0 else (-1 if dx < 0 else 0)
            self._diag_arming = None
            self._diag_done = True          # 一轮只斜跳一次（这一拍才算真跳了 ✓）
            self._diag_flying = True        # 跳出去 ⇒ 进"飞行相"（见上面那段 ✓）
            self._diag_y0 = None if py is None else float(py)
            self._diag_left = False
            self._diag_at = float(now)
            self._press_dir = _sgn
            self._press_at = now
            self.note = ("斜跳上绳：离绳 %.0f px（区间 %d~%d）⇒ **按跳**"
                         "（方向键上一拍已经发过 ✓）"
                         % (dx, self.near_px, self.jump_start_px))
            # ⚠ 竖直方向**一律 ↑**（`vert=1`，不是 `self.dir`）：用户给的条件是
            #   "**空中吸附绳梯要按住 ↑**" —— 下爬那一跳也在空中，同样得按 ↑ 才吸得上
            #   （吸上之后才由 ③ 那一相按 ↓ 往下走 ✓）。
            return self._out(_sgn, True, vert=1)   # 朝绳走 + 按跳 + 按住 ↑ ✓
        if abs(dx) > self.tol_px:
            self._in_tol_since = None
            sign = 1 if dx > 0 else -1
            # ---- ①' **斜跳上绳**（用户 2026-09-27 的设计）----
            # 原话："现在利用「起跳距离范围」设计「斜跳上绳」逻辑，要求使用「开始对齐绳梯x
            # 的距离」参数兼容旧的「对齐x原地起跳上绳」逻辑" ⇒ 一段里**两个区间**：
            #   · `开始对齐绳梯x的距离`(near_px) < |dx| ≤ `起跳距离`(jump_start_px)
            #     ⇒ **斜跳**：按住朝绳的方向 + 点按跳（斜着过去 ✓，省掉"站住再原地跳"那段 ✓）；
            #   · |dx| ≤ near_px ⇒ **老逻辑一个字没改**（点按对齐 → 站住 → 原地起跳 ✓）；
            #   · |dx| > 起跳距离 ⇒ 老逻辑"一口气按住走"（离太远斜跳够不着 ✗）。
            # ⚠ 这里原来还有一道"人得站在绳底那块面上"的许可（`_at_entry` ✓）—— 2026-09-27
            #   用户明确否掉（"**对齐了就按跳开始爬啊，不需要判定别的**" ✓）⇒ 与原地起跳
            #   **同一道门一起拆** ✓（口径只有一条：**对齐 x 就按跳** ✓）。
            # ⚠ **一轮只斜跳一次**（`_diag_done` ✓）：跳完继续朝绳走 ⇒ 近了自然交回老逻辑；
            #   每拍都按跳就成了"一路乱跳" ✗（`retry()` / 被打断重走时会重新武装 ✓）。
            # ⚠ `jump_start_px` = 0（默认）⇒ 整条**关掉** ⇒ 与加这个功能之前**完全一致** ✓。
            if (self.jump_start_px and abs(dx) > self.near_px
                    and abs(dx) <= self.jump_start_px
                    and not self._diag_done):
                # ⭐ **第 1 拍：只发"朝绳走"**（用户 2026-09-28 要求："斜跳也**先发方向键、
                #   下一拍再按跳**" ✓）—— 同一次 tick 里把"方向"和"跳"一起发，游戏里未必算
                #   "按住方向再跳"（`KeyState` 一次下发多个键**不保证顺序** ✗），与
                #   「跳下绳梯」那条**同一个理由** ✓ ⇒ 记下"起手了"（`_diag_arming` ✓），
                #   **这一拍不按跳** ✓（下一拍照样要跳，哪怕已经进容差 ✓，见 `update` 顶上那段）。
                self._diag_arming = float(now)
                self._press_dir = sign      # 记成"正按着这边"（对齐延迟的记账要一致 ✓）
                self._press_at = now
                self.note = ("斜跳上绳：离绳 %.0f px（区间 %d~%d，且人正站在这块面上）"
                             "⇒ **先按住 %s 朝绳走**（下一拍再按跳 ✓）"
                             % (dx, self.near_px, self.jump_start_px,
                                "→" if sign > 0 else "←"))
                # ⚠ 竖直方向**一律 ↑**（`vert=1`）—— 空中吸附绳梯的条件就是"正在按住 ↑" ✓
                return self._out(sign, False, vert=1)   # 只朝绳走 + 按住 ↑（**不按跳** ✓）
            # 「**对齐绳梯移动延迟(ms)**」（用户 2026-09-27 加的参数）：对齐 x 时
            # **两次按下方向键之间至少要隔这么久**。怎么算"一次按下"：**同方向的连续
            # 按住算一次**（`_press_dir` 记着现在按着哪边）—— 所以远距离那种"一口气
            # 按住走"天然满足 ✓（而且远距离点按会走得太慢、直接撞超时 ✗）。
            # 真正受它约束的是**快到位时的一下一下点按**（原来写死的 `TAP_PERIOD_S`
            # 周期就是这里的默认值 ✓）：按够 `TAP_ON_S` 就松开，下一次按要等间隔到 ✓。
            _held = (self._press_dir == sign)
            _since = (None if self._press_at is None
                      else float(now) - self._press_at)
            if (_held and abs(dx) <= self.near_px
                    and (float(now) - self._press_at) >= TAP_ON_S):
                # 点按的"松开那一下"（快到位时别一路蹭过去 = 冲过头 ✓）
                self._press_dir = 0
                self.note = "微调：差 %.0f px（松开这一拍，别冲过头）" % dx
                return self._out(0, False)
            if (not _held and _since is not None and self.align_gap_ms > 0
                    and _since * 1000.0 < self.align_gap_ms):
                # 上一次按下还没到「移动延迟」⇒ 这一拍**不按**（站住等）——
                # 过冲之后往回按（换了方向）也走这条 ⇒ 不会在绳两边来回抖 ✓
                self._press_dir = 0
                self.note = "对齐中：差 %.0f px（等移动延迟 %d ms）" % (
                    dx, self.align_gap_ms)
                return self._out(0, False)
            # ⚠ **只有"新的一次按下"才记时刻**（2026-09-27 修）：原来这里每一拍都写
            #   `_press_at = now` ⇒ `now - _press_at` 永远只有**一帧**（决策跟着收流帧
            #   跑，≈30fps 时一帧 33ms），而上面那条"按够 `TAP_ON_S`(60ms) 就松开"正是
            #   拿它算的 ⇒ **永不成立** ⇒ 进了「开始对齐绳梯x的距离」以内也一直**按住
            #   不放** ✗（用户 2026-09-27 报的"对齐 x 时方向键按了很久"就是这个：
            #   一帧 29~33ms < 60ms ⇒ 松开那一条永远不满足 ⇒ 变成一口气按住走）。
            #   按住期间**不刷**它 ⇒ "松开"是从**按下那一下**起算的，与帧率无关 ✓。
            if not _held:
                self._press_at = now
            self._press_dir = sign
            if abs(dx) <= self.near_px:
                # 已经走近了 ⇒ 斜跳**重新武装**（这一轮的下一次"离远"还能再试一次 ✓）
                self._diag_done = False
                self.note = "微调：差 %.0f px（点按 %s）" % (
                    dx, "→" if sign > 0 else "←")
            else:
                self.note = "对齐中：差 %.0f px（容许 %d）" % (dx, self.tol_px)
            return self._out(sign, False)
        # ⭐ **本轮还没发过方向键 ⇒ 先朝绳点按一次**（用户 2026-09-28 要求，原话："朝目标绳梯
        #   的 x 方向对齐 x（**至少发 1 次点按方向键**）→ 跳 → 按住 ↑，这三步要循环"）。
        #   ⛔ 原来这一支直接"站住等 `hold_ms` ⇒ 跳"，**一次方向键都不发** ✗ —— 用户要的是
        #   **每一轮都真的朝绳发过一下**才跳 ✓（`_align_pressed` 由 `_out` 一处记账 ✓：
        #   按跳那拍会清掉它 ⇒ 下一轮又要点一次 ✓）。
        #   ⚠ `dx == 0`（正对绳、没有方向可依）⇒ **不硬点**（点哪边都是把人推离绳 ✗）✓。
        #   ⚠ 点完把站住窗口**重新起算**（`_in_tol_since = None`）：那一下可能把人挪出/挪进
        #     容差 ⇒ 让"进容差 ⇒ 站住 `hold_ms` ⇒ 跳"照旧从**发完键之后**算 ✓。
        if not self._align_pressed and abs(dx) > 1e-9:
            _sgn = 1 if dx > 0 else -1
            self._align_pressed = True      # 这一拍就发（`_out` 里也会置 ✓，这儿写明白）
            self._press_dir = _sgn
            self._press_at = now
            self._in_tol_since = None
            self.note = ("对齐 x：本轮还没发过方向键 ⇒ **先朝绳点按一次 %s**"
                         "（差 %.0f px，已在容许 %d 以内 ✓）"
                         % ("→" if _sgn > 0 else "←", dx, self.tol_px))
            return self._out(_sgn, False)
        self._press_dir = 0            # 进误差范围 ⇒ 方向键松开（"站住等" ✓）
        # 已经对齐了（|dx| ≤ tol）⇒ 斜跳**重新武装**：这一轮的下一次"离远"还能再试 ✓
        self._diag_done = False
        # ⚠ 但**"跳没上去、回来重来"那一轮例外**：那几拍方向键要继续按着
        #   （`_retrying`，用户原话"按跳 + 按住 ↑"）—— 中间松手，人到绳边上那一下
        #   就抓不住 ✗（真抓上了会被上面的"已在绳上"接走 ✓）。
        _hold = bool(self._retrying)
        if self._in_tol_since is None:
            self._in_tol_since = now
            self.note = "进误差范围了（差 %.0f px）—— 站住等 %d ms" % (
                dx, self.hold_ms)
            if self.hold_ms > 0:
                return self._out(0, False, hold_dir=_hold)   # 要等就这一拍先站住
            # 不要等（hold=0）⇒ **同一拍就上绳**，别白拖一拍
        if (now - self._in_tol_since) * 1000.0 < self.hold_ms:
            return self._out(0, False, hold_dir=_hold)   # 保持中，别动（动就把对齐弄丢了）
        # ⚠ **按跳的许可条件**（用户 2026-09-27："对齐 x 时一直在不正确的位置按跳"）：
        #   ⚠ 2026-09-27 起**只看 x**：对齐（`tol_px` 容差 + `hold_ms` 站住 ✓）⇒ 直接按跳 ✓
        #     （用户原话："对齐了就按跳开始爬啊，不需要判定别的" ✓）。
        #   不满足 ⇒ **绝不按跳**（跳了也抓不到，只会"在不对的位置一直按跳"✗），
        #   但**保持窗口不重算**（`_in_tol_since` 不动）⇒ 人一落到那块面上就能立刻跳 ✓。
        # ⭐ 用户 2026-09-27 明确（原话）："**对齐了就按跳开始爬啊，不需要判定别的**" ⇒
        #   这里**不再有**"按跳许可"那道门（原来要求 `_at_entry` = 人站在绳底那块面上 ✓）。
        # 为什么拆掉（用户当天连着两次踩到）：
        #   ① 绳的两端常常**不属于同一个集合**（截图那条爬边是「三楼 → 顶层」：绳底那块面
        #      #99 属「三楼」、人脚下 #74 属「顶层」）⇒ 那个判据本身就没意义 ✗；
        #   ② 就算同一个集合，y 也常差十几像素（读数口径 / 站的深浅 ✓）⇒ 门一直拦着，
        #      人**站着不动** ✗（用户原话："这个卡住了"）。
        # ⇒ "对齐 x" 才是能不能按跳的**唯一**前提 ✓；跳了没上去由下面的"点按 / 重来"
        #   那一小段 + 「寻路超时」兜底 ✓（那条链一个字没动 ✓）。
        self.phase = self.CLIMB
        self._retrying = False
        # ⭐ **「对齐完成、即将起跳」这个时刻**（用户 2026-09-28 要求 ✓）：agent 要在这一刻
        #   复核一次"有没有更便宜的怪"（见 `agent._climb_recheck` ✓）⇒ 这里把时刻记下来，
        #   外面靠 `getattr(job, "_armed_at", None)` 观察它（同一个字段 `DropJob` 也有 ✓
        #   —— 那边就是进 `ARMED` 相的那一刻 ✓ 口径一致 ✓）。
        # ⚠⚠ **如实说一句**：本执行器"对齐完成"与"按跳"在**同一拍**内发生
        #   （`_align_step` 返回 None ⇒ 同一次 `update` 里紧接 `_climb_step` 就 `_jump_tried = True`
        #   ✓，见下面 759 那一段）⇒ agent 最早只能在**下一拍**看到这个时刻 ⇒ 那一下跳**已经发出去了**
