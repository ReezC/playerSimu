        #: ⚠ 跳那一拍只在 `_retry_stage == ""` 时才按 ⇒「**后续的跳**」自然也排在
        #:   "稳定 + 点按 + 对齐"完成之后 ✓（用户 2026-09-27 原话的后半句）。
        self._retry_stage = ""
        #: 「跳没上去 ⇒ 回到对齐 x 重新开始」**之前**那一次**目标方向（↑/↓）的点按**
        #: 是从哪一刻起算的（用户 2026-09-27 要求；None = 没在点按）。
