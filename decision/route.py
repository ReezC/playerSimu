        #: ⇒ 用纯值 ✓（用户 2026-09-28 重新审视："↑ 键也要再按这么多时间后再松"，明确
        #: 用纯 align_hold_ms，不再额外加端到端延迟）。
        self.base_hold_ms = max(0, int(hold_ms))
        self.timeout_s = float(timeout_s)
        #: 第几次尝试（失败重来会 +1，见 `retry`）—— ⚠ **只用来算重试等待的增量**，
        #: 不再是"上限"了（用户 2026-09-27：不设最多试几次，由「寻路超时时间」收口 ✓）。
        self.attempt = 1
        self.phase = self.ALIGN
        self.note = "对齐到 %s 的 x=%.0f（容许 ±%d px，要稳 %d ms）" % (
            self.ladder_id, self.x, self.tol_px, self.hold_ms)
        self._t0 = None
        self._in_tol_since = None
        self._off_since = None             # 从哪一刻起不在绳上（判"掉下来了"，带容错期）
        #: 有没有某一拍读到过"脚下已经是目标集合"。**只做提示/日志**，不作到达依据
        #:（到达是纯几何的，见 `_arrived`）。
        self._saw_dst_set = False
        #: 第一次判到达的时刻 + 那一刻定下的"再按住方向键多久"（毫秒）+ 到达那句话。
        #: 到达≠立刻松手（用户 2026-09-26 要求），见 update 里那段。
        self._arrived_at = None
        self._arrived_hold = 0
        self._arrived_why = ""
        # ---- 下爬（dir < 0）专属的三个锚点（见 `_jump_down_beat` / `_y_settled`）----
        #: 判定"已在绳上"的那一拍（None = 还没判定上绳）。**下爬**要在这儿起算
        #: "坐标对齐误差时间"（在绳上稳住这么久 ⇒ 松 ↓ 跳下去，用户 2026-09-26 定的）。
        self._on_ladder_since = None
        #: 「**确实确认过在绳上**」—— 感知说在绳上就记下；之后就算感知说不在（多半是
        #: **我们自己刚松开 ↑**，比如"点按重试"那几拍 ✓），只要**位置还在绳段里**就保持
        #: "在绳上"✓（真离开绳段才清 ✓）。存在理由：感知那份 `ladder_id` 带**按键许可**
        #: （没按 ↑/↓ 一律不算 ✓），而执行器自己会松键 ⇒ 只看它就会**自己把自己判成没上绳** ✗
        #: ⇒ 走"点按 / 回对齐"⇒ 又松键 ⇒ 原地打转（用户 2026-09-27 报的"执行器说没上" ✓）。
        #: ⚠ 它是**布尔**、不是时刻，**别**加进 `_ANCHORS`（那张表 `_resume` 会给它加 dt ✗）。
        self._rope_seen = False
        #: 上一拍 `_out` 请他按的**竖直键**（+1 上 / -1 下 / 0 没按 ✓）—— 用来判"这一拍感知
        #: 说不在绳上"是不是**我们自己松的键**（见 `update` 里那段 ✓）。
        self._last_vert = 0
