def stall_s_from_retry_ms(ms):
    """「移动操作尝试间隔(ms)」→ 那些"多久没进展就算卡住"的判据要的**秒**（下限 0.5 ✓）。

    用户 2026-09-27 要求（原话）："移除卡住判定时长(s)，**统一采用移动操作尝试间隔(ms)**" ✓
    —— 原来那件 `DecisionSettings.stall_s` 已删 ✓；上爬「爬不动」/ 下爬「等落地」/ 跳跃「没落到」
    这些判据现在都从这一件参数换算 ✓。
    **一处实现**：三处调用（`agent.start_climb` 灌 job ✓、实时线程的解析器 ✓、面板预览 ✓）
    都走它 ⇒ 免得三处各写一份钳法、以后又分叉 ✗（下限 0.5 秒：再小就等于"刚按一下就判卡住"✗）。
    """
    try:
        n = int(ms)
    except (TypeError, ValueError):
        n = 3000
    return max(0.5, n / 1000.0)

