    def cancel(self, why="取消"):
        if self.phase not in (self.DONE, self.FAILED):
            self.phase = self.FAILED
            self.note = str(why)
        return self._out(0, False)

    # ---- 内部 ----

    @staticmethod
    def _span_dist(px, spot):
        """`px` 到那条 foothold 的 **x 范围**的距离：在范围里 = 0，否则＝到**最近端点**的距离 ✓。"""
        left, right, _fid = spot
