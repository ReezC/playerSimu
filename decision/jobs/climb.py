                _why = self._mid_landed(now, py, on_rope)
                if _why is None:
                    return self._mid_jump_beat(now, px)      # 还在落 ⇒ 走那一相的时序 ✓
                self._mid_land_at = now                      # = 用户说的"**返回成功**"那一刻 ✓
