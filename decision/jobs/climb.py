        # ⚠ 与 `JUMP_DOWN` **同一个理由**必须排在"不在绳上 ⇒ 判掉下来了"那条**之前** ✗：
        #   这一相本来就是**主动**离开绳（跳下来 ✓）⇒ `ladder_id` 当然没了 ⇒ 拿它判"掉下来了"
