        # ---- ①'' **斜跳飞行中：朝绳走 + 按住 ↑**（用户 2026-09-27 现场）----
        # 原话："现在斜跳上绳梯会有「**经过绳梯却没有上去**」的现象，**空中吸附绳梯的
        #   条件是「正在按住 ↑」**"。
        # 为什么单开这一段：斜跳是"按住朝向 + 跳"跳出去的 ✓，但**跳完那一拍**开始就走回
        #   下面的对齐逻辑了 —— 它每拍发的是"**只按水平方向**"（`_out(sign, False)`
