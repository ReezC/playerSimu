        self._align_best = abs(float(dx))      # 跳完重新起锚 ✓
        self._align_best_at = float(now)
        self._press_dir = sign                  # 记账与"按住方向"一致 ✓
        self._press_at = now
        self.note = ("对齐走不动：离绳 %.0f px，%.1fs 没靠近（平台边缘 / 小台阶？）"
                     "⇒ **跳一下**（第 %d/%d 次，「走不动按跳」✓）"
                     % (dx, self.stall_s, self._align_hops, self.ALIGN_STALL_HOPS))
