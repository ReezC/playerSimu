            #   「（再按住 ↑ N ms 再松…）」✓，这里一覆盖 ⇒ **日志里的 `route_phase` 和状态栏
            #   那句就只剩纯 why** ✗ ⇒ 人看着就像"那一下不做了" ✗（**行为其实照做** ✓
