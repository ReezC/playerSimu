        #: ⚠ 只有**上爬**（`dir > 0`）走这条路（下爬本来就有它自己的"跳下绳梯"✓ 见 `JUMP_DOWN`）。
        self.mid_dir = str(mid_dir or "")
        self.mid_y = None if mid_y is None else float(mid_y)
        #: ⭐⭐ **「先上绳、再按 mid_y 定方向」**（用户 2026-10-19 ✓ 原话：
