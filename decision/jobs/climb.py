    def _y_settled(self, now, py, still_s=None):
        """「等待 y 稳定」：y 已经不再变了 ⇒ 算落地（用户定的最后一步）。

        **复用现成的两个数**（`STALL_GAIN_PX` / 时长，不新造 —— 它们本来就是
        "y 动没动"那套判据用的：小地图读数在抖，动过 2px 才算"在动"；连续静一会儿算稳）。
        没有 y 读数（定位掉帧）时**不判** —— 那是观测问题，不是"落稳了"。

        `still_s`：要安静多久算稳（秒）。**None = `self.stall_s`**（设置里那格
        「卡住判定时长(s)」✓）。⭐ 2026-10-01 起「跳失败后等 y 稳定」那条**已删**（改由
        位置状态权威广播的 `here_sets` 判"还站在起跳平台"✓）⇒ 本方法只剩**下爬落地 /
        中途跳下**在用 ✓。
        """
        if py is None:
            return False
        _still = (self.stall_s if still_s is None
                  else max(0.0, float(still_s)))
        pyv = float(py)
        if self._y_ref is None or abs(pyv - self._y_ref) >= STALL_GAIN_PX:
            self._y_ref = pyv
            self._y_still_since = now
            return False
        return (self._y_still_since is not None
                and (now - self._y_still_since) >= _still)

